import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {exportTXT,exportMarkdown,exportCSV,exportDOCX} from './exporter.mjs';
const fixture=JSON.parse(await readFile(new URL('./fixture.json',import.meta.url),'utf8'));
const clean={document:fixture,title:'HỌP ĐIỀU HÀNH – Hải Phòng',includeTimestamps:false};
const marked={...clean,includeTimestamps:true};
const txt=exportTXT(clean),txtM=exportTXT(marked),md=exportMarkdown(clean),mdM=exportMarkdown(marked),csv=exportCSV(clean),csvM=exportCSV(marked),docx=exportDOCX(clean),docxM=exportDOCX(marked);
let count=0;function check(name,fn){fn();console.log('PASS',name);count++;}
check('Unicode TXT',()=>assert.match(txt,/Hải Phòng/));
check('literal hardbreak TXT',()=>assert.match(txt,/xuống dòng\nTiếng Việt/));
check('blank paragraph TXT',()=>assert.match(txt,/tiếng, Hải Phòng\n\n•/));
check('clean TXT no marks',()=>assert.doesNotMatch(txt,/rec-01@/));
check('marked TXT time',()=>assert.match(txtM,/rec-01@01:02:03\.456/));
check('unlinked TXT',()=>assert.match(txtM,/không liên kết âm thanh/));
check('Markdown heading',()=>assert.match(md,/##/));
check('Markdown bold',()=>assert.match(md,/\*\*đồng chí/));
check('Markdown italic',()=>assert.match(md,/\*Tiếng Việt/));
check('Markdown marked vs clean',()=>{assert.doesNotMatch(md,/rec\\-01@/);assert.match(mdM,/rec\\-01@/);});
check('CSV BOM',()=>assert.equal(csv.charCodeAt(0),0xfeff));
check('CSV CRLF',()=>assert.match(csv,/\r\n/));
check('CSV quoting',()=>assert.match(csv,/"Cụm dán từ Word: ""A,B""/));
check('CSV clean no mark columns',()=>assert.doesNotMatch(csv,/audioOffsetMs/));
check('CSV marked columns',()=>assert.match(csvM,/"audioOffsetMs"/));
check('CSV unlinked',()=>assert.match(csvM,/"unlinked-01","","","1794756200000","unlinked","false"/));
check('DOCX ZIP signature',()=>assert.deepEqual([...docx.slice(0,2)],[80,75]));
check('DOCX OOXML parts',()=>assert.match(new TextDecoder().decode(docx),/word\/document.xml/));
check('DOCX modes',()=>{assert.ok(docxM.length>docx.length);assert.match(new TextDecoder().decode(docxM),/rec-01@/);});
check('deterministic output',()=>assert.deepEqual(exportDOCX(marked),docxM));
console.log('TOTAL',count,'PASS');
